#!/usr/bin/env bash
# Regenerate pkglist/repo.txt and pkglist/aur.txt from what is explicitly
# installed on this machine, so a rebuild can install everything in one pass:
#
#   grep -v '^#' pkglist/repo.txt | sudo pacman -S --needed -
#   grep -v '^#' pkglist/aur.txt  | paru -S --needed -
#
# Runs from cron just before the 3am nightly backup, which commits and pushes
# any change. Safe to run by hand.
set -euo pipefail

D="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/pkglist"
mkdir -p "$D"

# Not reinstallable from the AUR by name: debug splits, and credential-broker-bin,
# which is built from ~/Sites/credential-broker/packaging/aur/credential-broker-bin.
skip='(-debug$|^credential-broker-bin$)'

{
  echo "# Official-repo packages explicitly installed on $(uname -n). Generated by"
  echo "# scripts/pkglist-refresh.sh; edit the machine, not this file. Needs multilib."
  pacman -Qqen | grep -Ev "$skip"
} > "$D/repo.txt.new"

{
  echo "# Foreign (AUR) packages explicitly installed on $(uname -n). Generated by"
  echo "# scripts/pkglist-refresh.sh. Not listed: credential-broker-bin (build it from"
  echo "# ~/Sites/credential-broker/packaging). openvpn3 needs --nocheck; waybar-git"
  echo "# needs its conflict prompt answered (see docs/setting-up-archlinux.md)."
  pacman -Qqem | grep -Ev "$skip"
} > "$D/aur.txt.new"

for f in repo aur; do
  if cmp -s <(grep -v '^#' "$D/$f.txt.new") <(grep -v '^#' "$D/$f.txt" 2>/dev/null); then
    rm "$D/$f.txt.new"
  else
    mv "$D/$f.txt.new" "$D/$f.txt"
  fi
done
